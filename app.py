@socketio.on('join_game')
def handle_join(data):
    team_name = data['team_name']
    player_id = request.sid
    
    if player_id not in game_state["players"]:
        game_state["players"][player_id] = {
            "name": team_name,
            "position": 0,
            "stats": INITIAL_STATS.copy(),
            "color": f"#{random.randint(0x50, 0xFF):02x}{random.randint(0x20, 0x90):02x}{random.randint(0x10, 0x60):02x}",
            "skip_turns": 0
        }
        if player_id not in game_state["player_order"]:
            game_state["player_order"].append(player_id)
            
    emit('update_state', game_state, broadcast=True)

@socketio.on('roll_dice')
def handle_roll():
    player_id = request.sid
    if len(game_state["player_order"]) == 0 or game_state["player_order"][game_state["turn_index"]] != player_id:
        return

    player = game_state["players"][player_id]
    
    # Проверка пропуска ходов (Опала)
    if player.get("skip_turns", 0) > 0:
        player["skip_turns"] -= 1
        emit('update_state', game_state, broadcast=True)
        # Передаем ход дальше
        game_state["turn_index"] = (game_state["turn_index"] + 1) % len(game_state["player_order"])
        emit('update_state', game_state, broadcast=True)
        return

    dice_result = random.randint(1, 6)
    old_pos = player["position"]
    new_pos = (old_pos + dice_result) % game_state["board_size"]
    player["position"] = new_pos
    
    emit('update_state', game_state, broadcast=True)
    
    # Выбор события: клетки-опалы (каждая 10-я), кризисы (каждая 5-я), шансы (каждая 7-я) или вопросы
    if new_pos == 10 or new_pos == 25 or new_pos == 35:
        event_data = random.choice([e for e in EVENTS_BANK if e["type"] == "опала"])
    elif new_pos % 5 == 0 and new_pos != 0:
        event_data = random.choice([e for e in EVENTS_BANK if e["type"] == "кризис"])
    elif new_pos % 7 == 0 and new_pos != 0:
        event_data = random.choice([e for e in EVENTS_BANK if e["type"] == "шанс"])
    else:
        event_data = random.choice([e for e in EVENTS_BANK if e["type"] == "вопрос"])
        
    emit('trigger_event', {"event": event_data, "player_id": player_id}, broadcast=True)

@socketio.on('submit_answer')
def handle_answer(data):
    player_id = request.sid
    delta = data.get('delta', {})
    skip = data.get('skip_turns', 0)
    
    if player_id in game_state["players"]:
        player = game_state["players"][player_id]
        for stat, val in delta.items():
            if stat in player["stats"]:
                player["stats"][stat] = max(0, player["stats"][stat] + val)
        if skip > 0:
            player["skip_turns"] = skip
                
    emit('update_state', game_state, broadcast=True)

@socketio.on('end_turn')
def handle_end_turn():
    game_state["turn_index"] = (game_state["turn_index"] + 1) % len(game_state["player_order"])
    emit('update_state', game_state, broadcast=True)

